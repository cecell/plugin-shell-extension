"""gen_ctda_params.py <TES5Edit\\Core\\wbDefinitionsTES5.pas> <out.inc>

Generates src/itm_ctda.inc: for every Skyrim condition function, how xEdit
compares its two parameters ('F' = FormID, 'I' = ignored, 'V' = value).
A parameter with no declared type is ptNone, which xEdit ignores, as it does
ptString (wbConditionParameters {1} and {4}).
"""
import re
import sys

FORMID_FIRST = 24  # TConditionParameterType: ptActor (24) .. ptWorldspace (57) are FormIDs


def main():
    src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    enum = re.search(r"TConditionParameterType = \((.*?)\);", src, re.S).group(1)
    names = re.findall(r"\{(\d+)\}\s*(pt\w+)", enum)
    kind = {}
    for num, name in names:
        n = int(num)
        if name in ("ptNone", "ptString"):
            kind[name.lower()] = "I"
        elif n >= FORMID_FIRST:
            kind[name.lower()] = "F"
        else:
            kind[name.lower()] = "V"
    rows = []
    for m in re.finditer(r"\(Index:\s*(\d+);\s*Name:\s*'([^']*)'([^)]*)\)", src):
        idx, name, rest = int(m.group(1)), m.group(2), m.group(3)
        p1 = re.search(r"ParamType1:\s*(pt\w+)", rest)
        p2 = re.search(r"ParamType2:\s*(pt\w+)", rest)
        k1 = kind[p1.group(1).lower()] if p1 else "I"
        k2 = kind[p2.group(1).lower()] if p2 else "I"
        rows.append((idx, k1, k2, name))
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_ctda_params.py from TES5Edit Core\\wbDefinitionsTES5.pas.\n")
        f.write("// This Source Code Form is subject to the terms of the Mozilla Public License,\n")
        f.write("// v. 2.0. If a copy of the MPL was not distributed with this file, You can obtain\n")
        f.write("// one at https://mozilla.org/MPL/2.0/.\n")
        f.write("// {function index, param1, param2}: F = FormID, I = ignored, V = value.\n")
        for idx, k1, k2, name in sorted(rows):
            f.write(f"{{{idx}, '{k1}', '{k2}'}},  // {name}\n")
    print(f"{len(rows)} functions -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
